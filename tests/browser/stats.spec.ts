import { test, expect } from '@playwright/test'
import { encode } from 'msgpack-lite'

test('season stats charts, filters, downloads and table work across themes', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Stats', exact: true }).click()
  await expect(page).toHaveURL(/\/stats\/$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Season stats')
  await expect(page.locator('.stats-plot svg')).toHaveCount(4)
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.locator('.stats-season-table tbody tr')).toHaveCount(39)
  await expect(page.getByRole('link', { name: 'JSON', exact: true })).toHaveAttribute('href', '/stats.json')
  await expect(page.getByRole('link', { name: 'MessagePack', exact: true })).toHaveAttribute('href', '/stats.msgpack')
  const counts = page.getByRole('region', { name: 'New and Leftovers', exact: true })
  await counts.getByRole('button', { name: 'New', exact: true }).click()
  await counts.getByRole('button', { name: 'Leftovers', exact: true }).click()
  await expect(counts.getByText('Select a series above.')).toBeVisible()
  await counts.getByRole('button', { name: 'New', exact: true }).click()
  await counts.getByRole('button', { name: 'Leftovers', exact: true }).click()
  const mix = page.getByRole('region', { name: 'TV and ONA', exact: true })
  await expect(mix.locator('svg')).toContainText('100%')
  await mix.getByRole('button', { name: 'Counts', exact: true }).click()
  await expect(mix.locator('svg')).not.toContainText('100%')
  await mix.getByRole('button', { name: 'Percentage', exact: true }).click()
  await mix.locator('svg').hover({ position: { x: 120, y: 120 } })
  await expect(mix.locator('.stats-tooltip')).toBeVisible()
  await expect(mix.locator('.stats-tooltip')).toContainText('%')
  await expect(mix.locator('.stats-tooltip')).toContainText('TV')
  const rating = page.getByRole('region', { name: 'Average rating', exact: true })
  await rating.locator('svg').hover({ position: { x: 120, y: 120 } })
  await expect(rating.locator('.stats-tooltip')).toContainText('contributing anime')
  const audience = page.getByRole('region', { name: 'Ratings and favourites', exact: true })
  await audience.getByRole('button', { name: 'Rating submissions', exact: true }).click()
  await expect(audience.getByRole('button', { name: 'Rating submissions', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByLabel('From year', { exact: true }).selectOption('2026')
  await page.getByLabel('To year', { exact: true }).selectOption('2026')
  await expect(page.locator('.stats-season-table tbody tr')).toHaveCount(4)
  await expect(page.locator('.stats-season-table tbody tr').first()).toContainText('In progress')
  await page.getByRole('button', { name: 'All years' }).click()
  await expect(page.locator('.stats-season-table tbody tr')).toHaveCount(39)
  await page.getByRole('button', { name: 'light theme', exact: true }).click()
  const response = await page.reload()
  expect(response?.status()).toBe(200)
  await expect(page.locator('html')).toHaveClass(/light/)
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://kitsu.wopian.me/stats/')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.locator('.stats-season-table tbody').getByRole('link', { name: 'Autumn 2017', exact: true }).click()
  await expect(page.locator('.overview-counts p').nth(2)).toHaveText('91 New')
  await expect(page.locator('.overview-counts p').nth(3)).toHaveText('0 Leftovers')
  expect(errors).toEqual([])
})

test('stats keep rendered table on fetch failure, reject malformed payload and handle empty archives', async ({ page }) => {
  await page.route('**/stats.msgpack', (route) => route.fulfill({ status: 503, body: 'unavailable' }))
  await page.goto('/stats/')
  await expect(page.getByRole('alert')).toContainText('HTTP 503')
  await expect(page.locator('.stats-season-table tbody tr')).toHaveCount(39)
  await expect(page.locator('.stats-plot svg')).toHaveCount(0)
  await page.unroute('**/stats.msgpack')
  await page.route('**/stats.msgpack', (route) => route.fulfill({ body: encode({ version: 1, seasons: [] }) }))
  await page.getByRole('button', { name: 'Retry stats' }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid stats data')
  await page.unroute('**/stats.msgpack')
  await page.getByRole('button', { name: 'Retry stats' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.stats-plot svg')).toHaveCount(4)
  await page.route('**/stats.msgpack', (route) => route.fulfill({ body: encode({ version: 1, updated: null, uniqueAnime: 0, seasons: [] }) }))
  await page.reload()
  await expect(page.getByText('No archived seasons available.')).toBeVisible()
  await expect(page.locator('.stats-season-table tbody tr')).toHaveCount(0)
})
